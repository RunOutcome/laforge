// Writes THIRD_PARTY_NOTICES.md: the licence of every third-party package
// that ships inside la (Go modules compiled into it on any release platform,
// and the npm packages bundled into the web client), with the full text.
// The same file goes into the web client as notices.txt, so the binary
// carries it, and into every release archive and the container image.
//
//   node scripts/notices.mjs          # write
//   node scripts/notices.mjs --check  # fail if the committed file is stale
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const check = process.argv.includes('--check');

function licenceFile(dir) {
  if (!dir || !existsSync(dir)) return null;
  const name = readdirSync(dir).find((f) => /^(licen[cs]e|copying|ofl)(\.(md|txt))?$/i.test(f));
  return name ? readFileSync(join(dir, name), 'utf8').trim() : null;
}

// Go: modules whose packages are compiled into ./cmd/la on each release target.
const goModules = new Map();
for (const [goos, goarch] of [['darwin', 'arm64'], ['linux', 'amd64'], ['windows', 'amd64']]) {
  const out = execFileSync('go', ['list', '-deps', '-f', '{{with .Module}}{{if not .Main}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}{{end}}', './cmd/la'], {
    cwd: root,
    env: { ...process.env, GOOS: goos, GOARCH: goarch, CGO_ENABLED: '0' },
    encoding: 'utf8',
  });
  for (const line of out.split('\n').filter(Boolean)) {
    const [path, version, dir] = line.split('\t');
    goModules.set(path, { name: path, version, dir, ecosystem: 'Go module' });
  }
}

// The Go standard library is compiled into every binary too.
const goroot = execFileSync('go', ['env', 'GOROOT'], { cwd: root, encoding: 'utf8' }).trim();
const goVersion = execFileSync('go', ['env', 'GOVERSION'], { cwd: root, encoding: 'utf8' }).trim();
goModules.set('go', { name: 'Go standard library', version: goVersion.replace(/^go/, ''), dir: goroot, ecosystem: 'Go toolchain' });

function detect(text) {
  if (!text) return undefined;
  if (/Apache License[\s\S]*Version 2\.0/.test(text)) return 'Apache-2.0';
  if (/SIL OPEN FONT LICENSE/i.test(text)) return 'OFL-1.1';
  if (/Permission is hereby granted, free of charge/.test(text)) return 'MIT';
  if (/Permission to use, copy, modify, and(\/or)? distribute/.test(text)) return 'ISC';
  if (/Redistribution and use in source and binary forms/.test(text)) return /Neither the name/.test(text) ? 'BSD-3-Clause' : 'BSD-2-Clause';
  return undefined;
}

// npm: the packages the web client bundles (the lockfile's non-dev entries).
const lock = JSON.parse(readFileSync(join(root, 'web/package-lock.json'), 'utf8'));
const npm = [];
for (const [key, meta] of Object.entries(lock.packages)) {
  if (!key || meta.dev) continue;
  const name = key.replace(/^.*node_modules\//, '');
  npm.push({ name, version: meta.version, declared: meta.license, dir: join(root, 'web', key), ecosystem: 'npm package' });
}

// Fonts that built-in skins bundle (forge/skins/<skin>/fonts, with font.json and the licence).
const fonts = [];
const skinsDir = join(root, 'forge/skins');
for (const skin of existsSync(skinsDir) ? readdirSync(skinsDir) : []) {
  const dir = join(skinsDir, skin, 'fonts');
  if (!existsSync(join(dir, 'font.json'))) continue;
  const meta = JSON.parse(readFileSync(join(dir, 'font.json'), 'utf8'));
  fonts.push({ name: `${meta.name} (${skin} skin)`, version: meta.version, declared: meta.license, dir, ecosystem: 'font' });
}

// Libraries the forge bundles for skin scenes (forge/scenehost, vendor.json and the licence).
const sceneHost = join(root, 'forge/scenehost');
if (existsSync(join(sceneHost, 'vendor.json'))) {
  const meta = JSON.parse(readFileSync(join(sceneHost, 'vendor.json'), 'utf8'));
  fonts.push({ name: meta.name, version: meta.version, declared: meta.license, dir: sceneHost, ecosystem: 'vendored library' });
}

const entries = [...[...goModules.values()].sort((a, b) => a.name.localeCompare(b.name)), ...npm.sort((a, b) => a.name.localeCompare(b.name)), ...fonts];
let missing = [];
let body = `# Third-party notices

LaForge (\`la\`) is Apache-2.0. It includes the third-party software below,
each under its own licence, reproduced in full. Generated by
\`scripts/notices.mjs\`; do not edit by hand.

| Package | Version | Kind | Licence |
| --- | --- | --- | --- |
`;
for (const e of entries) body += `| ${e.name} | ${e.version} | ${e.ecosystem} | ${e.declared ?? detect(licenceFile(e.dir)) ?? 'see below'} |\n`;
for (const e of entries) {
  const text = licenceFile(e.dir);
  if (!text) missing.push(`${e.name}@${e.version} (${e.dir})`);
  body += `\n---\n\n## ${e.name} ${e.version}\n\n\`\`\`\n${text ?? 'LICENCE TEXT NOT FOUND'}\n\`\`\`\n`;
}
if (missing.length) {
  console.error('no licence file for:\n  ' + missing.join('\n  '));
  process.exit(1);
}

const targets = [join(root, 'THIRD_PARTY_NOTICES.md'), join(root, 'web/public/notices.txt')];
if (check) {
  const stale = targets.filter((t) => !existsSync(t) || readFileSync(t, 'utf8') !== body);
  if (stale.length) {
    console.error('stale: ' + stale.join(', ') + '\nrun: node scripts/notices.mjs');
    process.exit(1);
  }
  console.log(`notices current (${entries.length} packages)`);
} else {
  for (const t of targets) writeFileSync(t, body);
  console.log(`wrote notices for ${entries.length} packages`);
}
